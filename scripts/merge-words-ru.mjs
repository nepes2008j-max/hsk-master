// Write { hanzi: "русский перевод" } into src/data/words-ru-extra.ts. Usage: node scripts/merge-words-ru.mjs <results.json...>
import fs from "node:fs";
const data = Object.assign({}, ...process.argv.slice(2).map((f) => JSON.parse(fs.readFileSync(f, "utf8"))));
const body = Object.entries(data).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync("src/data/words-ru-extra.ts", `// Generated by scripts/local-ai-words-ru.mjs (reviewed). Russian glosses for words missing from translations-ru.\nexport const wordsRuExtra: Record<string, string> = {\n${body}\n};\n`);
console.log(Object.keys(data).length, "words written");
