// Write generated example sentences (JSON from local-ai-examples*.mjs) into src/data/examples-extra.ts.
// Pinyin is (re)computed here from the whole sentence (context aware), then grouped per word.
// Usage: node --no-warnings --experimental-strip-types scripts/merge-examples.mjs <examples.json...>
import fs from "node:fs";
import { createRequire } from "node:module";
const { pinyin } = createRequire(import.meta.url)("pinyin-pro");
const seg = new Intl.Segmenter("zh", { granularity: "word" });
const NAMES = new Set(["小明", "小红", "马克", "艾米丽", "北京", "中国"]);
function py(zh) {
  const words = [...seg.segment(zh)].map((w) => w.segment);
  const syl = pinyin(zh, { toneType: "symbol", type: "array", nonZh: "consecutive" });
  let i = 0;
  const parts = words.map((w) => {
    if (!/[一-鿿]/.test(w)) return w.replace(/，/g, ",").replace(/、/g, ",").replace(/。/g, ".").replace(/？/g, "?").replace(/！/g, "!").replace(/[“”「」]/g, "\"").replace(/：/g, ":"); // punctuation
    const n = [...w].length; let p = syl.slice(i, i + n).join(""); i += n;
    return NAMES.has(w) ? p[0].toUpperCase() + p.slice(1) : p;
  });
  return parts.join(" ").replace(/\s+([,.?!:])/g, "$1").replace(/\s+$/, "").replace(/^./, (c) => c.toUpperCase());
}
const data = Object.assign({}, ...process.argv.slice(2).map((f) => JSON.parse(fs.readFileSync(f, "utf8"))));
for (const v of Object.values(data)) v.pinyin = py(v.hanzi);
const body = Object.entries(data).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync("src/data/examples-extra.ts", `// Generated by scripts/local-ai-*examples.mjs (pinyin via pinyin-pro, reviewed). Do not edit by hand.
export interface ExtraExample { hanzi: string; pinyin: string; english: string; ru: string }
export const examplesExtra: Record<string, ExtraExample> = {
${body}
};
`);
console.log(Object.keys(data).length, "examples written");
