// Write { "English text": "русский" } into src/data/exercise-ru.ts. Usage: node scripts/merge-exercise-ru.mjs <results.json...>
import fs from "node:fs";
const data = Object.assign({}, ...process.argv.slice(2).map((f) => JSON.parse(fs.readFileSync(f, "utf8"))));
const body = Object.entries(data).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync("src/data/exercise-ru.ts", `// Generated by scripts/local-ai-exercise-ru.mjs (reviewed). Keyed by the exact English text of an exercise.\nexport const exerciseRu: Record<string, string> = {\n${body}\n};\n`);
console.log(Object.keys(data).length, "exercise strings written");
